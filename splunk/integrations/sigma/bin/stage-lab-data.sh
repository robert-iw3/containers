#!/usr/bin/env bash
# Generate one canonical dataset and give the forwarder one set of inputs.
#
# Getting the parsing right took several passes, and each left a copy of
# the data in the index and a monitor stanza on the forwarder. The result
# reads like archaeology: four copies of the Windows events, only one of
# which parses, and dozens of inputs pointing at files long since read.
#
# This replaces all of it with a single generated dataset and a single
# inputs.conf, so what an operator reproduces is one clean ingest with
# known contents rather than the history of how it was arrived at.
#
#   ./bin/stage-lab-data.sh --uf epo-uat-uf
#   ./bin/stage-lab-data.sh --uf epo-uat-uf --seed 2026 --baseline 4000
#
# The dataset is labelled: scenario.py writes ground-truth.json beside the
# logs, naming which records are planted and at what level of
# sophistication, so what the engine then finds can be checked rather than
# admired.
set -euo pipefail

HERE="$(cd "$(dirname "$0")/.." && pwd)"
DATAGEN="$HERE/../datagen"
UF=""
INDEX="linux_lab"
SEED=2026
BASELINE=4000
WINDOW=4
OUT=""
APP="/opt/splunkforwarder/etc/apps/sigma_lab_inputs"

usage() { sed -n '2,18p' "$0"; exit "${1:-0}"; }

while [ $# -gt 0 ]; do
    case "$1" in
        --uf)       UF="${2:-}"; shift 2 ;;
        --index)    INDEX="${2:-}"; shift 2 ;;
        --seed)     SEED="${2:-}"; shift 2 ;;
        --baseline) BASELINE="${2:-}"; shift 2 ;;
        --window)   WINDOW="${2:-}"; shift 2 ;;
        --out)      OUT="${2:-}"; shift 2 ;;
        -h|--help)  usage 0 ;;
        *) echo "unknown argument: $1" >&2; usage 2 ;;
    esac
done
[ -n "$UF" ] || { echo "FAIL: --uf is required" >&2; exit 2; }
OUT="${OUT:-$(mktemp -d)}"

echo
echo "== Generate the labelled dataset =="
python3 "$DATAGEN/scenario.py" \
    --dataset "$DATAGEN/datasets/detection-validation.json" \
    --baseline-records "$BASELINE" --window-hours "$WINDOW" \
    --seed "$SEED" --out "$OUT" --index "$INDEX" 2>&1 | tail -6

echo
echo "== One set of inputs, replacing whatever accumulated =="
# Keep the previous inputs; this rewrites them and the old one is the only
# record of what was being read before.
podman exec "$UF" sh -c "test -f $APP/local/inputs.conf" 2>/dev/null && \
  podman exec -u root "$UF" sh -c \
    "cp $APP/local/inputs.conf $APP/local/inputs.conf.before-restage" || true

LAB="$APP/lab-logs/canonical"
podman exec -u root "$UF" sh -c "mkdir -p $LAB && chown -R ansible:ansible $APP/lab-logs"

conf=$(mktemp)
{
  echo "# One canonical dataset, generated by bin/stage-lab-data.sh."
  echo "# Regenerate it with the same --seed to get byte-identical input."
  echo "#"
  echo "# crcSalt makes the path part of what the fishbucket remembers, so"
  echo "# restaging under a new path is read again rather than skipped."
  echo
  for pair in \
      "XmlWinEventLog_Security.log|XmlWinEventLog:Security" \
      "XmlWinEventLog_Microsoft-Windows-Sysmon_Operational.log|XmlWinEventLog:Microsoft-Windows-Sysmon/Operational" \
      "sysmon_linux.log|sysmon:linux" \
      "linux_audit.log|linux_audit" \
      "linux_secure.log|linux_secure" \
      "bash_history.log|bash_history"; do
      f="${pair%%|*}"; st="${pair##*|}"
      printf '[monitor://%s/%s]\nsourcetype = %s\nindex = %s\nhost = sigma-lab\ndisabled = 0\ncrcSalt = <SOURCE>\n\n' \
             "$LAB" "$f" "$st" "$INDEX"
  done
} > "$conf"

for f in "$OUT"/*.log; do
    [ -f "$f" ] || continue
    podman cp "$f" "$UF:$LAB/$(basename "$f")"
done
podman cp "$conf" "$UF:$APP/local/inputs.conf"
podman exec -u root "$UF" sh -c "chown -R ansible:ansible $APP"
rm -f "$conf"

echo "  staged $(ls -1 "$OUT"/*.log 2>/dev/null | wc -l) file(s) under $LAB"
echo "  inputs.conf replaced; the previous one is kept as inputs.conf.before-restage"

echo
echo "== Restart the forwarder so it reads them =="
podman exec -u ansible "$UF" sh -c '/opt/splunkforwarder/bin/splunk restart >/dev/null 2>&1' || true
echo "  done"
echo
echo "  ground truth: $OUT/ground-truth.json"
echo
